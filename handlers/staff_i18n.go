// Staff and head-manager pages in Swedish and English.
//
// The English sentence is the key: {{tr "Table bookings"}} in a template,
// or st(lang, "Table bookings") in Go, gives "Bordsbokningar" in Swedish
// and the sentence itself in English. Sentences with numbers or names use
// %d / %s: {{trf "%d guests" .N}}. A test checks that every sentence used
// has a Swedish version.

// st translates a staff sentence.
func st(lang, s string) string {
	if lang == langSV {
		if t, ok := staffSV[s]; ok {
			return t
		}
	}
	return s
}

// stf translates a staff sentence and fills in the values.
func stf(lang, s string, a ...any) string { return fmt.Sprintf(st(lang, s), a...) }

// guestsCount: "1 guest" / "4 guests" / "4 gäster".
func guestsCount(lang string, n int) string {
	if n == 1 {
		return st(lang, "1 guest")
	}
	return stf(lang, "%d guests", n)
}

// monthName: "October" / "oktober".
func monthName(lang string, m time.Month) string {
	if lang == langSV {
		return monthsSV[m-1]
	}
	return m.String()
}

// monthShortL: "Oct" / "okt".
func monthShortL(lang string, m time.Month) string {
	if lang == langSV {
		return monthsSVs[m-1]
	}
	return m.String()[:3]
}

// monthYear: "October 2026" / "Oktober 2026".
func monthYear(lang string, t time.Time) string {
	return capitalize(monthName(lang, t.Month())) + " " + t.Format("2006")
}

// weekdayShortWD: "Mon" / "mån".
func weekdayShortWD(lang string, wd time.Weekday) string {
	if lang == langSV {
		return weekdaysSVs[wd]
	}
	return wd.String()[:3]
}

